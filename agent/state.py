from __future__ import annotations

from typing import Any, TypedDict


class AgentState(TypedDict, total=False):
    """
    המצב המשותף של סוכן החוגים

    המידע במצב עובר בין השלבים השונים בגרף
    ונשמר לאורך השיחה באמצעות הזיכרון של לנגרף

    המצב כולל את הודעת המשתמש
    תנאי החיפוש
    מצב ההבהרה
    מצב המשך השיחה
    תוצאות החיפוש
    ומידע הדרוש להצגת תוצאות נוספות
    """

    # -----------------------------------------------------
    # קלט המשתמש
    # -----------------------------------------------------

    user_message: str

    # סוג הבקשה שזוהה
    intent: str

    # האם הבקשה הובנה בביטחון סביר
    interpretation_confident: bool

    # -----------------------------------------------------
    # תנאי החיפוש
    # -----------------------------------------------------

    age: int | None

    category: str | None

    target_audience: str | None

    day: str | None

    start_after: str | None

    start_before: str | None

    location: str | None

    # -----------------------------------------------------
    # פרטי מרכז ומדריך
    # -----------------------------------------------------

    center_name: str | None

    branch: str | None

    instructor: str | None

    # -----------------------------------------------------
    # מצב הבהרה וניסיון הבנה נוסף
    # -----------------------------------------------------

    # האם כבר בוצע ניסיון נוסף להבין את הבקשה
    fallback_attempted: bool

    # מידע שחסר או לא הובן
    missing_information: list[str]

    # שאלת ההבהרה שמוצגת למשתמש
    clarification_question: str | None

    # האם המערכת מחכה להשלמת מידע מהמשתמש
    waiting_for_clarification: bool

    # -----------------------------------------------------
    # מצב השיחה והזיכרון
    # -----------------------------------------------------

    # סוג הפעולה שזוהתה בהודעה הנוכחית
    conversation_action: str | None

    # המידע החדש שהמשתמש הוסיף בהמשך השיחה
    query_fragment: str | None

    # תנאי חיפוש שהמשתמש ביקש להסיר
    clear_fields: list[str]

    # האם קיימות תוצאות נוספות להצגה
    waiting_for_more: bool

    # המיקום הנוכחי ברשימת התוצאות
    pagination_offset: int

    # -----------------------------------------------------
    # תוצאות החיפוש
    # -----------------------------------------------------

    tool_results: list[
        dict[str, Any]
    ]

    # -----------------------------------------------------
    # התשובה הסופית
    # -----------------------------------------------------

    final_answer: str